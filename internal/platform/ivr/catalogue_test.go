var update = flag.Bool("update", false, "rewrite telephony/prompts/catalogue.yaml")

const cataloguePath = "../../../telephony/prompts/catalogue.yaml"

type catalogue struct {
	Status string   `yaml:"status"`
	Sounds []string `yaml:"sounds"`
}

func requiredSounds(t *testing.T) []string {
	t.Helper()
	b, err := config.Load(os.DirFS("../../../config"))
	if err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile("../../../config/gated/gazetteer.yaml")
	if err != nil {
		t.Fatal(err)
	}
	g, err := location.ParseFile(raw)
	if err != nil {
		t.Fatal(err)
	}
	m, err := intake.NewMachine(b.Tool1, g, b.Intake.DispatchTriggerScreen)
	if err != nil {
		t.Fatal(err)
	}
	set := map[string]bool{}
	for _, pr := range m.AllPrompts() {
		for _, s := range Sounds(pr) {
			set[s] = true
		}
	}
	for _, s := range Fallback() {
		set[s] = true
	}
	for _, s := range AlertSounds(b.Tool1, b.Responder) {
		set[s] = true
	}
	for _, s := range OutboundSounds(b.Responder) {
		set[s] = true
	}
	for _, s := range BridgeSounds(b.Responder.Languages) {
		set[s] = true
	}
	for d := '0'; d <= '9'; d++ {
		set["sauti/digits/"+string(d)] = true
	}
	out := make([]string, 0, len(set))
	for s := range set {
		out = append(out, s)
	}
	slices.Sort(out)
	return out
}

// Every prompt the IVR can play is in the recording catalogue, and the
// catalogue lists nothing the IVR no longer plays. Run with -update after a
// Tool 1 or gazetteer change.
func TestPromptCatalogueIsComplete(t *testing.T) {
	want := requiredSounds(t)
	if *update {
		header := "# IVR prompt catalogue (Build Prompt §10.2; Guide §4). Generated by\n" +
			"# `go test ./internal/platform/ivr -run TestPromptCatalogueIsComplete -update`\n" +
			"# from the Tool 1 catalogue and the gazetteer. Each ID is one recording under\n" +
			"# Asterisk's sounds directory, spoken by a human in that language after forward\n" +
			"# and back translation and clinical sign-off. PLACEHOLDER: not yet recorded.\n"
		body, err := yaml.Marshal(catalogue{Status: "placeholder", Sounds: want})
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll("../../../telephony/prompts", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(cataloguePath, append([]byte(header), body...), 0o644); err != nil { //nolint:gosec // G306: committed, public file
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(cataloguePath)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	var cat catalogue
	if err := yaml.Unmarshal(raw, &cat); err != nil {
		t.Fatal(err)
	}
	missing, extra := diff(want, cat.Sounds), diff(cat.Sounds, want)
	if len(missing) > 0 || len(extra) > 0 {
		t.Fatalf("catalogue out of date (run with -update):\nmissing %s\nextra %s", strings.Join(missing, ", "), strings.Join(extra, ", "))
	}
}

func diff(a, b []string) []string {
	var out []string
	for _, x := range a {
		if !slices.Contains(b, x) {
			out = append(out, x)
		}
	}
	return out
}
